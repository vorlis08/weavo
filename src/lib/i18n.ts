/** Czech plural: 1 → forms[0], 2–4 → forms[1], else → forms[2] */
export function cz(n: number, forms: [string, string, string]) {
  if (n === 1) return forms[0]
  if (n >= 2 && n <= 4) return forms[1]
  return forms[2]
}

